"""Validated image processing and local upload storage."""

from __future__ import annotations

import os
import re
import tempfile
import warnings
from io import BytesIO
from pathlib import Path
from uuid import uuid4

from PIL import Image, ImageOps, UnidentifiedImageError


class InvalidImageError(ValueError):
    """Raised when an uploaded file is not an allowed, safe-to-process image."""


_FORMATS = {
    ".jpg": ("JPEG", ".jpg"),
    ".jpeg": ("JPEG", ".jpg"),
    ".png": ("PNG", ".png"),
    ".webp": ("WEBP", ".webp"),
}
_MAX_IMAGE_DIMENSION = 10_000
_MAX_IMAGE_PIXELS = 20_000_000


def save_uploaded_image(data: bytes, original_name: str, upload_folder: str) -> str:
    """Decode, normalize, and atomically store a raster image under a random name."""
    extension = Path(original_name).suffix.lower()
    expected_format = _FORMATS.get(extension)
    if expected_format is None:
        raise InvalidImageError("Only JPEG, PNG, and WebP images are allowed.")

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            image = Image.open(BytesIO(data))
            image_format = image.format
            image.verify()
            image = Image.open(BytesIO(data))
            if image_format != expected_format[0]:
                raise InvalidImageError("The file extension does not match its image format.")
            if (
                image.width > _MAX_IMAGE_DIMENSION
                or image.height > _MAX_IMAGE_DIMENSION
                or image.width * image.height > _MAX_IMAGE_PIXELS
            ):
                raise InvalidImageError("The image dimensions are too large.")
            image.load()
            image = ImageOps.exif_transpose(image)
            image.thumbnail((2_400, 2_400), Image.Resampling.LANCZOS)
    except InvalidImageError:
        raise
    except (
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
        UnidentifiedImageError,
        OSError,
    ) as error:
        raise InvalidImageError("The uploaded file is not a valid image.") from error

    image_format, output_extension = expected_format
    if image_format == "JPEG":
        image = image.convert("RGB")
    output = BytesIO()
    if image_format == "WEBP":
        image.save(output, format=image_format, method=6)
    else:
        image.save(output, format=image_format, optimize=True)
    filename = f"{uuid4().hex}{output_extension}"

    upload_path = Path(upload_folder)
    upload_path.mkdir(parents=True, exist_ok=True)
    temporary_path: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            dir=upload_path,
            prefix=".upload-",
            delete=False,
        ) as temporary_file:
            temporary_path = temporary_file.name
            temporary_file.write(output.getvalue())
        final_path = upload_path / filename
        os.replace(temporary_path, final_path)
    except OSError:
        if temporary_path is not None:
            try:
                os.unlink(temporary_path)
            except FileNotFoundError:
                pass
        raise
    return filename


def is_managed_image_filename(filename: str) -> bool:
    """Return whether a filename is one generated by this storage service."""
    return re.fullmatch(r"[a-f0-9]{32}\.(?:jpg|jpeg|png|webp)", filename) is not None
